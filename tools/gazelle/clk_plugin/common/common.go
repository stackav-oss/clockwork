// GetCppHdrRuleName returns the rule name for a cpp header
func GetCppHdrRuleName(name string) string {
	name = strings.Join(strings.Split(name, "/"), "::")
	if strings.HasSuffix(name, cppProtoHdrSuffix) {
		return strings.TrimSuffix(name, cppProtoHdrSuffix) + cppProtoRuleSuffix
	}
	return strings.TrimSuffix(name, getSuffix(name))
}

// IsClkSource returns true if the given file name ends with ".clk"
func IsClkSource(name string) bool {
	suffix := getSuffix(name)
	return suffix == ClkFileSuffix
}

func getSuffix(name string) string {
	idx := strings.LastIndex(name, ".")
	if idx < 0 {
		return ""
	}
	return name[idx:]
}

const clkRepo = "clockwork"

// GetClockworkLabelString gets a label for an object in the clockwork repo given
// a label string. It will prepend @clockwork to the label string if we are not
// building in the clockwork repo.
func GetClockworkLabelString(labelStr string, inClockworkRepo bool) string {
	if !inClockworkRepo {
		return "@" + clkRepo + labelStr
	}
	return labelStr
}

// GetClockworkTargetString gets an import string for a target in the clockwork repo given
// an import string. It will prepend @clockwork:: to the target string if "clockwork" is
// in the external repos.
func GetClockworkTargetString(labelStr string, inClockworkRepo bool) string {
	if !inClockworkRepo {
		return "@" + clkRepo + "::" + labelStr
	}
	return labelStr
}

// Create a list of strings from a set of strings
func SortedStringsFromStringSet(stringSet map[string]bool) []string {
	result := []string{}
	for str := range stringSet {
		result = append(result, str)
	}
	slices.Sort(result)
	return result
}

// Create a list of ClkImport from a set of strings
func SortedClkImportsFromStringSet(stringSet map[string]bool) []ClkImport {
	result := []ClkImport{}
	for str := range stringSet {
		if strings.HasPrefix(str, "@") {
			str = strings.TrimPrefix(str, "@")
			parts := strings.Split(str, "::")
			repo := parts[0]
			importPath := ""
			if len(parts) > 1 {
				importPath = strings.Join(parts[1:], "::")
			}
			result = append(result, ClkImport{Repo: repo, ImportPath: importPath})
		} else {
			result = append(result, ClkImport{Repo: "", ImportPath: str})
		}
	}
	slices.SortFunc(result, func(a, b ClkImport) int {
		cmpResult := strings.Compare(a.Repo, b.Repo)
		if cmpResult != 0 {
			return cmpResult
		}
		return strings.Compare(a.ImportPath, b.ImportPath)
	})
	return result
}

// Set the generate attribute from the generate strings
func SetGenerateAttr(r *rule.Rule, generates []string) {
	const generatesAttr = "generate"
	r.DelAttr(generatesAttr)
	if len(generates) != 0 {
		generates = util.SSliceDedup(generates)
		slices.Sort(generates)
	} else {
		generates = []string{"none"}
	}
	r.SetAttr(generatesAttr, generates)
}
