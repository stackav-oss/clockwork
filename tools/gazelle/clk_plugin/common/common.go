// An import parsed from a clk use statement
type ClkImport struct {
	Repo       string
	ImportPath string
}

// ImportsParsedFromRuleSources is the "imports" interface returned by Language.GenerateRules(), and
// passed by Gazelle to Resolver.Resolve().
type ImportsParsedFromRuleSources interface {
	// GetClkGenerate returns the clockwork generate value
	GetClkGenerate() bool
	// GetClkGenerate returns the targets generated by the rule
	GetClkGenerates() []string
	// GetClkImports returns the imports for any clockwork targets
	GetClkImports() []ClkImport
	// GetCppImports returns the imports for cpp targets
	GetCppImports() []ClkImport
	// GetProtoImports returns the imports for proto targets
	GetProtoImports() []ClkImport
	// GetPyImports returns the imports for py targets
	GetPyImports() []ClkImport
	// GetCppExeImports() returns the imports for cpp_exe targets
	GetCppExeImports() []ClkImport
	// GetGoProtoImportPath returns the go protobuf import path or empty string if not set
	GetGoProtoImportPath() string
}

